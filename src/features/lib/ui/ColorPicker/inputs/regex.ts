//0 - 100 int
export const zeroTo100Regex = /^(0|[1-9][0-9]?|100)$/
//0 - 360 int
export const zeroTo360Regex = /^(?:36[0]|3[0-5][0-9]|[12][0-9][0-9]|[1-9]?[0-9])?$/i
//0.0 - 1.0 float
export const zeroTo1Regex = /^(0(\.[0-9]+)?|1(\.0+)?)$/
//0 - 255 int
export const zeroTo255Regex = /^([01]?[0-9][0-9]?|2[0-4][0-9]|25[0-5])$/i
